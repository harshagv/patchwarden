"""Builds the WordPress plugin zip, with the address of this Patchwarden baked into includes/config.php."""

from __future__ import annotations

import io
import re
import zipfile

from ..config import PROJECT_ROOT
from ..errors import AppError

PLUGIN_DIR = PROJECT_ROOT / "wordpress-plugin" / "patchwarden"
_SAFE_URL = re.compile(r"^https?://[A-Za-z0-9.-]+(?::\d{1,5})?(?:/[A-Za-z0-9._~/-]*)?$")


def config_php(api_url: str) -> str:
    if not _SAFE_URL.match(api_url):
        raise AppError(500, "bad_public_url", "PUBLIC_BASE_URL is not a plain http(s) address.")
    return ("<?php\n/**\n * Generated by Patchwarden when the plugin was downloaded. Contains no key or secret.\n */\n\n"
            "defined( 'ABSPATH' ) || exit;\n\n"
            "if ( ! defined( 'PATCHWARDEN_API_URL' ) ) {\n"
            f"\tdefine( 'PATCHWARDEN_API_URL', '{api_url}' );\n"
            "}\n")


def build_plugin_zip(api_url: str) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for path in sorted(PLUGIN_DIR.rglob("*")):
            rel = path.relative_to(PLUGIN_DIR.parent).as_posix()
            if path.is_file() and not rel.endswith("includes/config.php"):
                z.write(path, rel)
        z.writestr("patchwarden/includes/config.php", config_php(api_url))
    return buf.getvalue()
